//! Generates the advance-width tables `ui.measure-text` reads
//! (src/measure.rs): per font file Pitwall draws tiles' text with, a sorted
//! `(char, advance)` slice and a sorted `(left, right, adjustment)` slice of
//! kerning pairs, in font units, from the app's own font files, shaped as
//! Pitwall shapes them. Nothing is read at run time, and the host stays
//! without GPUI.

use std::fmt::Write as _;
use std::path::Path;

use rustybuzz::{Face, UnicodeBuffer};

/// Punctuation and symbols labels use beyond Latin-1.
const PUNCTUATION: &str = "–—‘’‚“”„…•‹›€™←↑→↓↔⌘⌥⇧⏎·";

/// Characters the tables cover: printable ASCII, Latin-1, Latin
/// Extended-A and the punctuation (the ones a font has). Everything else
/// counts as the average lowercase advance.
fn covered() -> Vec<char> {
    let mut chars: Vec<char> = (0x20u32..0x7f).chain(0xa0..0x180).filter_map(char::from_u32).collect();
    chars.extend(PUNCTUATION.chars());
    chars
}

/// Characters whose pairs are kerned: printable ASCII and the punctuation.
fn kerned() -> Vec<char> {
    let mut chars: Vec<char> = (0x20u32..0x7f).filter_map(char::from_u32).collect();
    chars.extend(PUNCTUATION.chars());
    chars
}

/// The shaped advance of `text`, in font units.
fn shaped(face: &Face, text: &str) -> i32 {
    let mut buffer = UnicodeBuffer::new();
    buffer.push_str(text);
    let glyphs = rustybuzz::shape(face, &[], buffer);
    glyphs.glyph_positions().iter().map(|p| p.x_advance).sum()
}

/// Writes table `name` for the font at `path`; its units per em.
fn table(name: &str, path: &Path, kern: bool, out: &mut String) -> u16 {
    println!("cargo:rerun-if-changed={}", path.display());
    let data = std::fs::read(path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
    let face = Face::from_slice(&data, 0).unwrap_or_else(|| panic!("parsing {}", path.display()));
    let advance = |c: char| face.glyph_index(c).and_then(|g| face.glyph_hor_advance(g));
    let lower: Vec<u16> = ('a'..='z').filter_map(advance).collect();
    let average = lower.iter().map(|&a| a as u32).sum::<u32>() / lower.len().max(1) as u32;
    let mut rows: Vec<(char, u16)> = covered().into_iter().filter_map(|c| advance(c).map(|a| (c, a))).collect();
    rows.sort();
    rows.dedup_by_key(|r| r.0);
    writeln!(out, "pub const {name}_FALLBACK: u16 = {average};").unwrap();
    writeln!(out, "pub static {name}: &[(char, u16)] = &[").unwrap();
    for (c, a) in &rows {
        writeln!(out, "    ({c:?}, {a}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    let mut pairs = Vec::new();
    if kern {
        let kerned = kerned();
        for &a in &kerned {
            for &b in &kerned {
                let (Some(wa), Some(wb)) = (advance(a), advance(b)) else { continue };
                let adjustment = shaped(&face, &format!("{a}{b}")) - wa as i32 - wb as i32;
                if adjustment != 0 {
                    pairs.push((a, b, adjustment));
                }
            }
        }
        pairs.sort();
    }
    writeln!(out, "pub static {name}_KERN: &[(char, char, i16)] = &[").unwrap();
    for (a, b, k) in pairs {
        writeln!(out, "    ({a:?}, {b:?}, {k}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub const {name}_UPEM: u16 = {};", face.units_per_em()).unwrap();
    face.units_per_em() as u16
}

fn main() {
    let fonts = Path::new(env!("CARGO_MANIFEST_DIR")).join("../pitwall-app/assets/fonts");
    let mut out = String::from("// Generated by build.rs from crates/pitwall-app/assets/fonts. Do not edit.\n");
    for (name, file, kern) in [
        ("INTER_REGULAR", "Inter-Regular.ttf", true),
        ("INTER_MEDIUM", "Inter-Medium.ttf", true),
        ("INTER_SEMIBOLD", "Inter-SemiBold.ttf", true),
        ("INTER_BOLD", "Inter-Bold.ttf", true),
        // Monospaced: no kerning (its ligatures keep their cells' width).
        ("MONO_REGULAR", "JetBrainsMono-Regular.ttf", false),
        ("MONO_SEMIBOLD", "JetBrainsMono-SemiBold.ttf", false),
        ("MONO_BOLD", "JetBrainsMono-Bold.ttf", false),
    ] {
        table(name, &fonts.join(file), kern, &mut out);
    }
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("text_widths.rs");
    std::fs::write(dest, out).unwrap();
}

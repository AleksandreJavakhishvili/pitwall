//! Generates Inter's width table (layout-lld.md §1): per weight, a sorted
//! `(char, advance)` slice and a sorted `(left, right, adjustment)` slice of
//! kerning pairs, in font units, so the guest can size labels before the SDK
//! can measure text (hla.md §3.7, gap G2).

use std::fmt::Write as _;
use std::path::Path;

use rustybuzz::{Face, UnicodeBuffer};

/// Punctuation labels use beyond Latin-1. Pitwall's Inter has no arrows or
/// `⌘` (the host falls back to another font): those count as the average.
const PUNCTUATION: &str = "–—‘’‚“”„…•‹›€™";

/// Characters the table covers: printable ASCII, Latin-1 and the punctuation
/// that labels use. Everything else counts as the average lowercase advance.
fn covered() -> Vec<char> {
    let mut chars: Vec<char> =
        (0x20u32..0x7f).chain(0xa0..0x100).filter_map(char::from_u32).collect();
    chars.extend(PUNCTUATION.chars());
    chars
}

/// Characters whose pairs are kerned: printable ASCII and the punctuation.
fn kerned() -> Vec<char> {
    let mut chars: Vec<char> = (0x20u32..0x7f).filter_map(char::from_u32).collect();
    chars.extend(PUNCTUATION.chars());
    chars
}

/// The shaped advance of `text`, in font units.
fn shaped(face: &Face, text: &str) -> i32 {
    let mut buffer = UnicodeBuffer::new();
    buffer.push_str(text);
    let glyphs = rustybuzz::shape(face, &[], buffer);
    glyphs.glyph_positions().iter().map(|p| p.x_advance).sum()
}

fn table(name: &str, path: &Path, out: &mut String) -> u16 {
    let data = std::fs::read(path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
    let face = Face::from_slice(&data, 0).unwrap_or_else(|| panic!("parsing {}", path.display()));
    let advance = |c: char| face.glyph_index(c).and_then(|g| face.glyph_hor_advance(g));
    let lower: Vec<u16> = ('a'..='z').filter_map(advance).collect();
    let average = lower.iter().map(|&a| a as u32).sum::<u32>() / lower.len().max(1) as u32;
    let mut rows: Vec<(char, u16)> =
        covered().into_iter().filter_map(|c| advance(c).map(|a| (c, a))).collect();
    rows.sort();
    rows.dedup_by_key(|r| r.0);
    writeln!(out, "pub const {name}_FALLBACK: u16 = {average};").unwrap();
    writeln!(out, "pub static {name}: &[(char, u16)] = &[").unwrap();
    for (c, a) in &rows {
        writeln!(out, "    ({c:?}, {a}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    let kerned = kerned();
    let mut pairs = Vec::new();
    for &a in &kerned {
        for &b in &kerned {
            let (Some(wa), Some(wb)) = (advance(a), advance(b)) else { continue };
            let adjustment = shaped(&face, &format!("{a}{b}")) - wa as i32 - wb as i32;
            if adjustment != 0 {
                pairs.push((a, b, adjustment));
            }
        }
    }
    pairs.sort();
    writeln!(out, "pub static {name}_KERN: &[(char, char, i16)] = &[").unwrap();
    for (a, b, k) in pairs {
        writeln!(out, "    ({a:?}, {b:?}, {k}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    face.units_per_em() as u16
}

fn main() {
    let fonts = Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/fonts");
    let regular = fonts.join("Inter-Regular.ttf");
    let semibold = fonts.join("Inter-SemiBold.ttf");
    println!("cargo:rerun-if-changed={}", regular.display());
    println!("cargo:rerun-if-changed={}", semibold.display());
    let mut out = String::from("// Generated by build.rs from assets/fonts. Do not edit.\n");
    let upem = table("REGULAR", &regular, &mut out);
    let upem_semibold = table("SEMIBOLD", &semibold, &mut out);
    assert_eq!(upem, upem_semibold, "both weights must share units per em");
    writeln!(out, "pub const UNITS_PER_EM: u16 = {upem};").unwrap();
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("inter_widths.rs");
    std::fs::write(dest, out).unwrap();
}
